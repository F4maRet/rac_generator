"""
Очистка текста перед подстановкой в документ (и сразу после генерации).

Главное правило: НОРМАЛЬНЫЙ текст (абзацы через пустую строку, без разметки
и служебных символов) проходит через эти функции БЕЗ ЕДИНОГО изменения -
документ из него получается побайтно тем же, что и раньше (это проверяется
сравнением с эталоном). Исправляется только то, что раньше портило документ:

  * абзацы, разделённые ОДНИМ переводом строки (так отвечают многие модели) -
    раньше весь раздел становился одним абзацем с принудительными разрывами
    строк, и Word при выравнивании по ширине растягивал каждую строку перед
    разрывом, а красная строка была только у первого абзаца;
  * остатки markdown («### Заголовок», «**жирный**», «- пункт») - раньше
    попадали в документ как есть;
  * управляющие символы (например, разрыв страницы \\x0c из текста,
    скопированного из PDF) - раньше сборка документа падала с ошибкой.
"""
import re

# Символы, недопустимые в XML документа Word: на них python-docx падает с
# "All strings must be XML compatible". \t, \n, \r допустимы, но в однострочных
# полях и в тексте разделов обрабатываются отдельно (см. ниже).
_XML_INVALID = re.compile("[\x00-\x08\x0b\x0c\x0e-\x1f￾￿]")

# «### Заголовок» -> «Заголовок»
_MD_HEADING = re.compile(r"^\s{0,3}#{1,6}\s+(.*?)\s*#*\s*$")
# «- пункт», «* пункт», «+ пункт», «• пункт» -> «– пункт» (обычное для русских
# технических текстов тире, а не дефис markdown). Тире «–»/«—» в начале строки
# не трогаем - это и есть нормальное оформление перечисления.
_MD_BULLET = re.compile(r"^\s*[-*+•▪·]\s+")
# горизонтальная линия markdown: «---», «***», «___»
_MD_RULE = re.compile(r"^\s*([-*_])(\s*\1){2,}\s*$")
# **жирный**, __жирный__, `код`
_MD_BOLD = re.compile(r"\*\*(.+?)\*\*|__(.+?)__", re.DOTALL)
_MD_CODE = re.compile(r"`([^`\n]+)`")


def single_line(value) -> str:
    """Для однострочных полей (ФИО, звание, должность, подписант): переводы
    строк и табуляции -> пробел, недопустимые для Word символы удаляются,
    пробелы по краям обрезаются (интерфейс и импорт и так присылают эти поля
    обрезанными). Обычные пробелы внутри НЕ схлопываются - чтобы не менять
    то, что раньше выглядело нормально."""
    if value is None:
        return ""
    s = str(value)
    s = re.sub(r"[\r\n\t\x0b\x0c]", " ", s)
    return _XML_INVALID.sub("", s).strip()


def _strip_inline_markdown(s: str) -> str:
    s = _MD_BOLD.sub(lambda m: m.group(1) if m.group(1) is not None else m.group(2), s)
    return _MD_CODE.sub(r"\1", s)


def body_paragraphs(text) -> list:
    """Текст раздела -> список абзацев для документа.

    Абзацем считается каждая непустая строка: в разделах рацпредложения нет
    случаев, когда нужен перенос строки ВНУТРИ абзаца, а вот одиночный перевод
    строки между абзацами встречается постоянно."""
    if text is None:
        return []
    if isinstance(text, (list, tuple)):
        text = "\n".join(str(x) for x in text)
    s = str(text)
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    s = s.replace("\x0c", "\n").replace("\x0b", "\n")  # разрыв страницы / верт. табуляция -> новый абзац
    s = s.replace("\t", " ")
    s = _XML_INVALID.sub("", s)
    s = _strip_inline_markdown(s)

    out = []
    for line in s.split("\n"):
        if _MD_RULE.match(line):
            continue
        m = _MD_HEADING.match(line)
        if m:
            line = m.group(1)
        line = _MD_BULLET.sub("– ", line, count=1)
        line = line.strip()
        if line:
            out.append(line)
    return out


def body_text(text) -> str:
    """То же, но обратно в строку (абзацы через пустую строку) - для показа
    в полях разделов сразу после генерации."""
    return "\n\n".join(body_paragraphs(text))


def clean_title(value) -> str:
    """Наименование из ответа модели: одна строка, без разметки, без кавычек
    вокруг всего названия и без точки в конце (по форме названия - без точки)."""
    s = _strip_inline_markdown(single_line(value)).strip()
    m = _MD_HEADING.match(s)
    if m:
        s = m.group(1).strip()
    pairs = {"«": "»", '"': '"', "'": "'", "“": "”", "„": "“"}
    if len(s) >= 2 and s[0] in pairs and s[-1] == pairs[s[0]]:
        s = s[1:-1].strip()
    if s.endswith(".") and not s.endswith(".."):
        s = s[:-1].rstrip()
    return s
